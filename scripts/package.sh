#!/usr/bin/env bash
# Packages an already-built `adf` binary into a release archive.
#
# Usage:
#   scripts/package.sh TARGET [VERSION]
#
#   TARGET   Rust target triple, for example aarch64-apple-darwin.
#   VERSION  Optional, X.Y.Z or vX.Y.Z. It must equal the version in Cargo.toml, so a binary can
#            never be packaged under the wrong release tag. Defaults to the Cargo.toml version.
#
# Local dry run on the host:
#   cargo build --locked --release && scripts/package.sh "$(rustc -vV | sed -n 's/^host: //p')"
#
# The binary is read from <target-dir>/TARGET/release/ (cargo build --release --target TARGET)
# or, when TARGET is the host triple, from <target-dir>/release/ (plain cargo build --release);
# if both exist, the newer one wins. <target-dir> is $CARGO_TARGET_DIR (relative paths are taken
# from the repository root) or target/.
#
# Output: <target-dir>/dist/adf-converter-vVERSION-TARGET.zip with one top-level directory
# adf-converter-vVERSION-TARGET/ that contains:
#   adf (adf.exe on Windows), README.md, LICENSE, THIRD_PARTY_NOTICES.md, CHANGELOG.md (if
#   present), docs/, skills/markdown-to-adf/ and completions/.
# The archive path is the only thing printed on stdout; progress goes to stderr.
#
# Shell completions are generated by running the packaged binary (`adf completions SHELL`). If
# the binary cannot be executed on this host at all (a cross build), completions/ is left out
# with a warning. Any other failure, including the binary exiting with an error, is fatal.
#
# Archiving uses Info-ZIP (`zip -9 -r -X`, keeps the executable bit) or, where zip is not
# installed (Windows runners), 7-Zip.
#
# Written for bash 3.2 (the /bin/bash of macOS runners): no associative arrays, no mapfile.
set -euo pipefail

die() {
  printf 'package.sh: error: %s\n' "$*" >&2
  exit 1
}
warn() {
  printf 'package.sh: warning: %s\n' "$*" >&2
}
info() {
  printf 'package.sh: %s\n' "$*" >&2
}

[[ $# -ge 1 && $# -le 2 ]] || die "usage: scripts/package.sh TARGET [VERSION]"
target=$1
requested_version=${2:-}
[[ $target =~ ^[A-Za-z0-9_.-]+$ ]] || die "invalid target triple: '$target'"

root=$(cd "$(dirname "$0")/.." && pwd)
cd "$root"

# --- Version -----------------------------------------------------------------------------------
# The first `version = "…"` line of the [package] table in Cargo.toml.
cargo_version=$(awk '
  /^[[:space:]]*\[/ { in_package = ($0 ~ /^[[:space:]]*\[package\][[:space:]]*(#.*)?$/); next }
  in_package && /^[[:space:]]*version[[:space:]]*=/ {
    sub(/^[^"]*"/, ""); sub(/".*$/, ""); print; exit
  }
' Cargo.toml)
semver='^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?(\+[0-9A-Za-z.-]+)?$'
[[ $cargo_version =~ $semver ]] || die "could not read the package version from Cargo.toml (got '$cargo_version')"
version=$cargo_version
if [[ -n $requested_version ]]; then
  requested_version=${requested_version#v}
  [[ $requested_version == "$cargo_version" ]] ||
    die "VERSION $requested_version does not match Cargo.toml version $cargo_version"
fi

# --- Binary ------------------------------------------------------------------------------------
exe=adf
case $target in
  *windows*) exe=adf.exe ;;
esac
target_dir=${CARGO_TARGET_DIR:-target}
host=$(rustc -vV 2>/dev/null | sed -n 's/^host: //p' || true)

bin="$target_dir/$target/release/$exe"
if [[ $target == "$host" && -f "$target_dir/release/$exe" ]]; then
  if [[ ! -f $bin || "$target_dir/release/$exe" -nt $bin ]]; then
    bin="$target_dir/release/$exe"
  fi
fi
[[ -f $bin ]] || die "no binary at $bin; build it first with: cargo build --locked --release --target $target"
info "packaging $bin (adf-converter $version, $target)"

# --- Stage -------------------------------------------------------------------------------------
name="adf-converter-v$version-$target"
mkdir -p "$target_dir/dist"
dist=$(cd "$target_dir/dist" && pwd)
stage="$dist/$name"
archive="$dist/$name.zip"
rm -rf "$stage" "$archive"
mkdir -p "$stage"

cp "$bin" "$stage/$exe"
chmod 0755 "$stage/$exe"

for file in README.md LICENSE THIRD_PARTY_NOTICES.md; do
  [[ -f $file ]] || die "missing required file: $file"
  cp "$file" "$stage/$file"
done
if [[ -f CHANGELOG.md ]]; then
  cp CHANGELOG.md "$stage/CHANGELOG.md"
else
  info "no CHANGELOG.md yet (release-please creates it with the first release); skipping it"
fi

[[ -d docs ]] || die "missing required directory: docs/"
cp -R docs "$stage/docs"

[[ -f skills/markdown-to-adf/SKILL.md ]] || die "missing required file: skills/markdown-to-adf/SKILL.md"
mkdir -p "$stage/skills"
cp -R skills/markdown-to-adf "$stage/skills/markdown-to-adf"

# Editor and OS litter must not end up in a release.
find "$stage" \( -name .DS_Store -o -name '*~' -o -name '*.swp' \) -exec rm -f {} +

# --- Completions -------------------------------------------------------------------------------
status=0
"$stage/$exe" --version >/dev/null 2>&1 || status=$?
case $status in
  0)
    mkdir -p "$stage/completions"
    # shell:file pairs; the file names are the ones clap_complete uses by convention.
    for pair in bash:adf.bash zsh:_adf fish:adf.fish powershell:_adf.ps1 elvish:adf.elv; do
      shell=${pair%%:*}
      file=${pair#*:}
      "$stage/$exe" completions "$shell" >"$stage/completions/$file" ||
        die "'adf completions $shell' failed"
      [[ -s "$stage/completions/$file" ]] || die "'adf completions $shell' printed nothing"
    done
    ;;
  126 | 127)
    warn "cannot execute the $target binary on this host (${host:-unknown host}); the archive has no completions/"
    ;;
  *)
    die "'adf --version' exited with status $status; refusing to package a broken binary"
    ;;
esac

# --- Archive -----------------------------------------------------------------------------------
(
  cd "$dist"
  if command -v zip >/dev/null 2>&1; then
    zip -9 -r -X -q "$name.zip" "$name"
  elif command -v 7z >/dev/null 2>&1; then
    7z a -tzip -mx=9 "$name.zip" "$name" >/dev/null
  else
    die "neither zip (Info-ZIP) nor 7z is installed"
  fi
)
rm -rf "$stage"

info "created $archive"
printf '%s\n' "$archive"
